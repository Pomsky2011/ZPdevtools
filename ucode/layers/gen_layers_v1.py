#!/usr/bin/env python3
"""Two scrolling background layers (+ sprites, later) as PPU microcode. See docs/ppu/layers.md.

Emits ppuasm and runs ppuasm on it. Everything hot is raw instructions with constants and jump targets held in
registers: a label-jump shorthand is 4 Preset E (2 cycles each) + the jump, ~11 cycles, and a 16-bit immediate is 8.

Milestone 1 (this file): BG0 + BG1 only, pixel scroll, a command mode for the harness and a free-running bench mode.

  gen_layers.py [-o out.bin] [--asm out.asm] [--cols N]
"""
import argparse
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PPUASM = os.path.join(HERE, "..", "..", "executables", "ppuasm")

# ---- PPU memory layout (mirrored in zp_layers_layout.h, which this script also writes) -------------------------
CODE_BASE = 0x0400      # $0000 holds a stub; $00E0 / $00F0-$00FF / $0200-$0207 / $0300-$034F are live ports
PAL = 0x5000            # 256 x BBGR16 (512 B), loaded once with PALETTE256
CTRL = 0x5A00           # control block, words (see CTRL_WORDS)
STACK = 0x5E00          # grows UP
MAP = (0x6000, 0xA000)  # 64x64 cells x 4 B = 16 KiB each
MAX_COLS = 33           # unrolled cell blocks per row
TILE_MODE = 2           # 16BBGR 8bpp: the 256-entry palette, so each layer can own an index range

CTRL_WORDS = ["CMD", "DONE", "SCX0", "SCY0", "SCX1", "SCY1", "NCOLS", "MODE", "COUNT", "BENCHBAND"]

REGS = dict(
    ZERO=4, C2=2, C8=3, FC=5, CLIPV=6, C512=7, C256=8, C64=9,
    A=10, W0=11, W1=12, Y=13, X=14, FOUR=15,          # X/Y are SETPOS operands: R0-R15 only
    BAND=16, ROW0=17, LAYER=18, MAPB=19, SCX=20, SCY=21, WY=22, TROW=23, O=24, TX=25, FX=26, N=27, N1=28, N2=29,
    T=30, T2=31, RETA=32, CMD=33, BLOCKSZ=35, ENDADDR=36, NCOLS=37, ROWA=38, CLIP0=41, CLIP1=42, T3=43,
    SP=61, PC=62, DP=63,
)

NO_TILEDRAW = False
lines = []
_lbl = [0]


def e(s=""):
    lines.append(s)


def r(name):
    return "R%d" % REGS[name] if REGS[name] < 59 else name


def li(reg, value):
    """Load a 16-bit constant or a label address (8 cycles)."""
    e("    TARREG 2, LSB, %s" % r(reg))
    e("    TARREG 3, MSB, %s" % r(reg))
    if isinstance(value, str):
        e("    SETBYTE 2, %s" % value)
        e("    SETBYTE 3, %s" % value)
    else:
        e("    SETBYTE 2, 0x%02X" % (value & 0xFF))
        e("    SETBYTE 3, 0x%02X" % ((value >> 8) & 0xFF))


def mov(dst, src):
    e("    CLR %s" % r(dst))
    e("    ADD %s, %s" % (r(dst), r(src)))


def ldw(dst, addr):
    li("T3", addr)
    e("    SETDP %s" % r("T3"))
    e("    MOV %s" % r(dst))


def stw(addr, src):
    li("T3", addr)
    e("    SETDP %s" % r("T3"))
    e("    MOVDP %s" % r(src))


def ctrl(name):
    return CTRL + 2 * CTRL_WORDS.index(name)


def label(name):
    e("%s:" % name)


def newlabel(prefix):
    _lbl[0] += 1
    return "%s_%d" % (prefix, _lbl[0])


def ret_via(reg):
    mov("PC", reg)
    e("    JMR")


# ---------------------------------------------------------------------------------------------------------------
BLOCK_INSTRS = 14       # per cell; the computed entry in draw_cells depends on this being exact
BLOCK_BYTES = BLOCK_INSTRS * 2


def emit_block():
    e("    SETDP %s" % r("A")); e("    MOV %s" % r("W0")); e("    ADD %s, %s" % (r("A"), r("C2")))
    e("    SETDP %s" % r("A")); e("    MOV %s" % r("W1")); e("    ADD %s, %s" % (r("A"), r("C2")))
    e("    ADD %s, %s" % (r("W1"), r("CLIPV")))          # row-clip bit when the band splits this tile row
    e("    SETTILEBANK %s" % r("W1"))                     # reg % 4: the bank in bits 0-1
    e("    SETTILE %s, %d" % (r("W0"), TILE_MODE))        # reg & $FF: the tile ID
    e("    SETDP %s" % r("FC"))
    e("    MOVDP %s" % r("W1"))                           # attrs in bits 2-5, $10 in the high byte pushes them
    e("    SETPOS %s, %s" % (r("X"), r("Y")))
    if not NO_TILEDRAW:
        e("    TILEDRAW")
    else:
        e("    NOP")                                         # measurement only: the issue cost without the blitter
    e("    ADD %s, %s" % (r("X"), r("C8")))


def emit_program(cols):
    e("; generated by gen_layers.py - do not edit")
    e("    JMR main")
    pad = (CODE_BASE - 10) // 2
    for _ in range(pad):
        e("    NOP")
    assert CODE_BASE >= 10

    # ---- init -------------------------------------------------------------------------------------------------
    label("main")
    li("SP", STACK)
    li("ZERO", 0); li("C2", 2); li("C8", 8); li("FC", 0x00FC); li("C512", 512); li("C256", 256); li("C64", 64)
    li("FOUR", 4); li("BLOCKSZ", BLOCK_BYTES); li("ENDADDR", "blocks_end"); li("CLIP0", 0x0204); li("CLIP1", 0x0206)
    li("T", PAL)
    e("    SETDP %s" % r("T"))
    e("    PALETTE256")

    # ---- main loop: a harness command, else the free-running bench -----------------------------------------------
    label("main_loop")
    ldw("CMD", ctrl("CMD"))
    e("    CMP %s, %s" % (r("CMD"), r("ZERO")))
    e("    JMZ check_bench")
    mov("BAND", "CMD")
    e("    DEC %s" % r("BAND"))
    e("    JSR render_band")
    li("T", 25)
    label("drain")                       # let the last blits retire before telling the harness
    e("    DEC %s" % r("T"))
    e("    CMP %s, %s" % (r("T"), r("ZERO")))
    e("    JNZ drain")
    stw(ctrl("DONE"), "CMD")
    stw(ctrl("CMD"), "ZERO")
    e("    JMR main_loop")

    label("check_bench")
    ldw("T", ctrl("MODE"))
    e("    CMP %s, %s" % (r("T"), r("ZERO")))
    e("    JMZ main_loop")
    ldw("BAND", ctrl("BENCHBAND"))
    e("    JSR render_band")
    e("    INC %s" % r("BAND"))
    li("T", 31)
    e("    CMP %s, %s" % (r("BAND"), r("T")))
    e("    JNG bench_ok")
    li("BAND", 1)
    label("bench_ok")
    stw(ctrl("BENCHBAND"), "BAND")
    ldw("T2", ctrl("COUNT"))
    e("    INC %s" % r("T2"))
    stw(ctrl("COUNT"), "T2")
    e("    JMR main_loop")

    # ---- render_band: BAND in, both layers drawn -------------------------------------------------------------------
    label("render_band")
    ldw("NCOLS", ctrl("NCOLS"))
    mov("ROW0", "BAND"); e("    MUL %s, %s" % (r("ROW0"), r("C8")))
    e("    CLR %s" % r("LAYER"))
    li("MAPB", MAP[0])
    label("layer_loop")
    mov("T", "LAYER"); e("    MUL %s, %s" % (r("T"), r("FOUR"))); e("    ADD %s, %s" % (r("T"), r("FOUR")))
    li("T2", ctrl("SCX0") - 4); e("    ADD %s, %s" % (r("T"), r("T2")))     # T = SCX0 + 4*LAYER - 4 + 4 ... see below
    e("    SETDP %s" % r("T")); e("    MOV %s" % r("SCX"))
    e("    ADD %s, %s" % (r("T"), r("C2"))); e("    SETDP %s" % r("T")); e("    MOV %s" % r("SCY"))
    # world row = (ROW0 + scrollY) mod 512 ; tile row and fine offset
    mov("WY", "ROW0"); e("    ADD %s, %s" % (r("WY"), r("SCY")))
    mov("T", "WY"); e("    INTDIV %s, %s" % (r("T"), r("C512"))); e("    MUL %s, %s" % (r("T"), r("C512")))
    e("    SUB %s, %s" % (r("WY"), r("T")))
    mov("TROW", "WY"); e("    INTDIV %s, %s" % (r("TROW"), r("C8")))
    mov("O", "TROW"); e("    MUL %s, %s" % (r("O"), r("C8")))
    mov("T", "WY"); e("    SUB %s, %s" % (r("T"), r("O"))); mov("O", "T")           # O = fine Y 0..7
    # tile column and fine X
    mov("TX", "SCX"); e("    INTDIV %s, %s" % (r("TX"), r("C8")))
    mov("FX", "TX"); e("    MUL %s, %s" % (r("FX"), r("C8")))
    mov("T", "SCX"); e("    SUB %s, %s" % (r("T"), r("FX"))); mov("FX", "T")
    # segment split at the map's right edge: n1 = min(ncols, 64 - tx), n2 = the rest (wrapping to column 0)
    mov("T", "C64"); e("    SUB %s, %s" % (r("T"), r("TX")))
    mov("N1", "NCOLS")
    e("    CMP %s, %s" % (r("N1"), r("T")))
    e("    JNG n1_ok")
    mov("N1", "T")
    label("n1_ok")
    mov("N2", "NCOLS"); e("    SUB %s, %s" % (r("N2"), r("N1")))

    # half 1: tile row TROW, top at ROW0 - O; clipped to [ROW0, ROW0 + 8 - O) when O != 0
    mov("Y", "ROW0"); e("    SUB %s, %s" % (r("Y"), r("O")))
    e("    CLR %s" % r("CLIPV"))
    e("    CMP %s, %s" % (r("O"), r("ZERO")))
    e("    JMZ half1_go")
    li("CLIPV", 0x20)
    e("    SETDP %s" % r("CLIP0")); e("    MOVDP %s" % r("ROW0"))
    mov("T", "ROW0"); e("    ADD %s, %s" % (r("T"), r("C8"))); e("    SUB %s, %s" % (r("T"), r("O")))
    e("    SETDP %s" % r("CLIP1")); e("    MOVDP %s" % r("T"))
    label("half1_go")
    mov("ROWA", "TROW")
    e("    JSR draw_row")

    # half 2 (only when O != 0): tile row TROW+1 (mod 64), top at ROW0 + 8 - O, clipped to [that, ROW0 + 8)
    e("    CMP %s, %s" % (r("O"), r("ZERO")))
    e("    JMZ half2_done")
    mov("T", "TROW"); e("    INC %s" % r("T"))
    mov("T2", "T"); e("    INTDIV %s, %s" % (r("T2"), r("C64"))); e("    MUL %s, %s" % (r("T2"), r("C64")))
    e("    SUB %s, %s" % (r("T"), r("T2")))
    mov("ROWA", "T")
    mov("Y", "ROW0"); e("    ADD %s, %s" % (r("Y"), r("C8"))); e("    SUB %s, %s" % (r("Y"), r("O")))
    e("    SETDP %s" % r("CLIP0")); e("    MOVDP %s" % r("Y"))
    mov("T", "ROW0"); e("    ADD %s, %s" % (r("T"), r("C8")))
    e("    SETDP %s" % r("CLIP1")); e("    MOVDP %s" % r("T"))
    e("    JSR draw_row")
    label("half2_done")

    # next layer
    e("    INC %s" % r("LAYER"))
    li("T", 0x4000); e("    ADD %s, %s" % (r("MAPB"), r("T")))
    e("    CMP %s, %s" % (r("LAYER"), r("C2")))
    e("    JNZ layer_loop")
    e("    RET")

    # ---- draw_row: ROWA = tile row number on entry (turned into a byte address here), TX FX N1 N2 Y CLIPV set ------------
    label("draw_row")
    e("    MUL %s, %s" % (r("ROWA"), r("C256"))); e("    ADD %s, %s" % (r("ROWA"), r("MAPB")))
    mov("A", "TX"); e("    MUL %s, %s" % (r("A"), r("FOUR"))); e("    ADD %s, %s" % (r("A"), r("ROWA")))
    e("    CLR %s" % r("X")); e("    SUB %s, %s" % (r("X"), r("FX")))
    mov("N", "N1")
    li("RETA", "dr_seg1")
    e("    JMR draw_cells")
    label("dr_seg1")
    mov("A", "ROWA")
    mov("X", "N1"); e("    MUL %s, %s" % (r("X"), r("C8"))); e("    SUB %s, %s" % (r("X"), r("FX")))
    mov("N", "N2")
    li("RETA", "dr_seg2")
    e("    JMR draw_cells")
    label("dr_seg2")
    e("    RET")

    # ---- draw_cells: N cells from A at (X, Y); enters the unrolled blocks N from the end ------------------------------------
    label("draw_cells")
    mov("T", "N"); e("    MUL %s, %s" % (r("T"), r("BLOCKSZ")))
    e("    CLR PC"); e("    ADD PC, %s" % r("ENDADDR")); e("    SUB PC, %s" % r("T"))
    e("    JMR")
    for i in range(MAX_COLS):
        label("blk_%d" % i)
        emit_block()
    label("blocks_end")
    ret_via("RETA")


def write_layout_header(path):
    with open(path, "w") as f:
        f.write("// generated by gen_layers.py - PPU layout of the two-layer + sprite microcode (docs/ppu/layers.md)\n")
        f.write("#pragma once\n")
        f.write("#define ZPL_CODE_BASE 0x%04X\n#define ZPL_PAL 0x%04X\n#define ZPL_CTRL 0x%04X\n" % (CODE_BASE, PAL, CTRL))
        f.write("#define ZPL_STACK 0x%04X\n#define ZPL_MAP0 0x%04X\n#define ZPL_MAP1 0x%04X\n" % (STACK, MAP[0], MAP[1]))
        f.write("#define ZPL_MAX_COLS %d\n#define ZPL_TILE_MODE %d\n" % (MAX_COLS, TILE_MODE))
        for i, n in enumerate(CTRL_WORDS):
            f.write("#define ZPL_CTRL_%s 0x%04X\n" % (n, CTRL + 2 * i))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-o", "--out", default=os.path.join(HERE, "build", "layers.bin"))
    ap.add_argument("--asm", default=None)
    ap.add_argument("--no-tiledraw", action="store_true", help="measurement variant: blocks issue everything but TILEDRAW")
    args = ap.parse_args()
    global NO_TILEDRAW
    NO_TILEDRAW = args.no_tiledraw
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    emit_program(MAX_COLS)
    asm = args.asm or os.path.splitext(args.out)[0] + ".asm"
    with open(asm, "w") as f:
        f.write("\n".join(lines) + "\n")
    write_layout_header(os.path.join(HERE, "zp_layers_layout_v1.h"))
    res = subprocess.run([PPUASM, asm, "-o", args.out], capture_output=True, text=True)
    sys.stdout.write(res.stdout)
    sys.stderr.write(res.stderr)
    if res.returncode != 0:
        sys.exit(res.returncode)
    print("%s: %d bytes of code (limit $%04X)" % (args.out, os.path.getsize(args.out), PAL))


if __name__ == "__main__":
    main()
