#!/usr/bin/env python3
"""Regenerate docs/apu/encodings.md: every APU instruction form, assembled by apuasm and read back by apudisasm.

An APU instruction is one 16-bit word: a 5-bit opcode and 11 operand bits. Each form below is assembled with the real
assembler; the word is split into its fields for the table, and disassembled again. A form whose disassembly does not
assemble back to the same word is reported (the disassembler is the second opinion on the assembler).

Run from anywhere:  python3 scripts/gen_apu_docs.py
"""
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
APUASM = os.path.join(ROOT, "executables", "apuasm")
APUDISASM = os.path.join(ROOT, "executables", "apudisasm")
OUT = os.path.join(ROOT, "docs", "apu", "encodings.md")

# (group, [syntax forms]). Jump forms that take a label are followed by a `target:` line when assembled.
FORMS = [
    ("Control flow", [
        "NOP 0", "NOP $100", "JMP target", "JMP 0, 1, $20", "JMP 0, 0, $20",
        "JNZ X, $20", "JNZ Y, $20", "JZ X, $20", "JZ X, 0, $20", "JZ Y, 1, $20",
        "JMS $20", "JSR $20", "JDP", "JDPS", "JMX", "JSX", "RET",
    ]),
    ("Page and pointer registers", [
        "SRP $80", "SDP $30", "SDP 0, $30", "SDP 1, $30", "SDB $12", "BSP", "PUDP", "PODP",
    ]),
    ("Constants, moves and stack", [
        "SCR X, 12", "SCR Y, 255", "LDA X, $12", "ZOR X", "ZOR Y", "MOV X, Y", "MOV Y, X", "EXC",
        "INC X", "INC Y", "INC DP", "INC SP", "DEC X", "DEC Y", "DEC DP", "DEC SP",
        "PUX", "PUY", "POX", "POY",
    ]),
    ("Memory", [
        "STA X, $10", "STA Y, $10", "STR $10, X", "STR $10, Y", "LDA X", "LDA Y", "STA X", "STA Y", "STA $12",
        "ZOA $10", "ZOA DP", "STRX X, Y", "STRX Y, X", "STAX X, Y", "STAX Y, X",
    ]),
    ("Arithmetic and logic", [
        "NOR X, Y, X", "NOR X, Y, $10", "AND X, Y, X", "AND X, Y, $10", "ADD X, Y, X", "ADD X, Y, $10",
        "SUB X, Y, X", "SUB X, Y, $10", "ADC X, Y, X", "ADC X, Y, $10", "SBC X, Y, X", "SBC X, Y, $10",
        "XOR X, Y, X", "XOR X, Y, $10", "CRB X, Y, X", "CRB X, Y, $10",
    ]),
    ("Flags", [
        "SFR $0", "CF $1", "SF $8", "STF X", "STF Y",
    ]),
    ("Branches", [
        "BEQ X, Y, $20", "BNE X, Y, $20", "BLT X, Y, $20", "BGT X, Y, $20",
        "CME X, Y, 0, $05", "CMN X, Y, 1, $05", "CMG X, Y, 0, $05", "CML X, Y, 1, $05",
    ]),
    ("Hardware loops", [
        "LST 0, 5", "LST 3, 40", "LFN 0", "LFN 3", "BRT $0", "BRP",
    ]),
]


def run(tool, *args):
    return subprocess.run([tool, *args], capture_output=True, text=True)


def assemble(form, d):
    src, out = os.path.join(d, "t.asm"), os.path.join(d, "t.bin")
    with open(src, "w") as f:
        f.write("%s\n NOP 0\ntarget: NOP 0\n" % form)
    if os.path.exists(out):
        os.remove(out)
    r = run(APUASM, src, out)
    if r.returncode != 0 or not os.path.exists(out):
        return None
    data = open(out, "rb").read()
    return (data[0] << 8) | data[1]       # big-endian words


def disassemble(word, d):
    binf = os.path.join(d, "w.bin")
    with open(binf, "wb") as f:
        f.write(bytes([word >> 8, word & 0xFF]))
    r = run(APUDISASM, binf)
    for line in r.stdout.splitlines():
        m = re.match(r"\s*[0-9A-Fa-f]+:?\s+(?:[0-9A-Fa-f]{4}\s+)?(.*)", line)
        if m and not line.lstrip().startswith(";"):
            return m.group(1).strip()
    return None


def main():
    lines = ["# APU instruction encodings\n",
             "<!-- GENERATED by scripts/gen_apu_docs.py from a live apuasm and apudisasm run: do not edit by hand. -->\n",
             "Every instruction is one 16-bit word, written big-endian: the top five bits are the opcode, the low eleven "
             "are operands. Each row below is a form that `apuasm` accepts, with the word it assembles to, split as "
             "`ooooo xxxxxxxxxxx`, and what `apudisasm` prints for that word. What each instruction does is in "
             "[instruction-set.md](instruction-set.md).\n"]
    bad = []
    with tempfile.TemporaryDirectory() as d:
        for group, forms in FORMS:
            lines.append("## %s\n" % group)
            lines.append("| Form | Word | `ooooo xxxxxxxxxxx` | Disassembles as |")
            lines.append("|------|------|--------------------|-----------------|")
            for form in forms:
                word = assemble(form, d)
                if word is None:
                    bad.append((form, "does not assemble"))
                    lines.append("| `%s` | not accepted | | |" % form)
                    continue
                dis = disassemble(word, d)
                bits = format(word, "016b")
                lines.append("| `%s` | `%04X` | `%s %s` | %s |" % (form, word, bits[:5], bits[5:], ("`%s`" % dis) if dis else ""))
                if dis:
                    again = assemble(dis, d)
                    if again != word:
                        bad.append((form, "disassembly `%s` assembles to %s, not %04X" % (
                            dis, "%04X" % again if again is not None else "nothing", word)))
            lines.append("")
    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    print("wrote", OUT)
    for form, why in bad:
        print("  %-22s %s" % (form, why))
    return 0


if __name__ == "__main__":
    sys.exit(main())
