#!/usr/bin/env python3
"""Regenerate docs/ppu/encodings.md: every PPU instruction form and every assembler shorthand, from live tool runs.

A PPU instruction is one 16-bit word, big-endian. Each form below is assembled with ppuasm, its word split into fields
and disassembled with ppudisasm; a form whose disassembly does not assemble back to the same word is reported. Each
shorthand is assembled and its real expansion printed by disassembling the bytes (not copied from a description).

Run from anywhere:  python3 scripts/gen_ppu_docs.py
"""
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PPUASM = os.path.join(ROOT, "executables", "ppuasm")
PPUDISASM = os.path.join(ROOT, "executables", "ppudisasm")
OUT = os.path.join(ROOT, "docs", "ppu", "encodings.md")

FORMS = [
    ("Basic instructions (opcodes 0-D)", [
        "DEFCALL R3, R4", "MOVXP R5", "NOP", "SWAPREG R1, R2", "CLR R5", "CMP R1, R2", "CLRF",
        "JMZ", "JMG", "JNZ", "JNG", "INC R5", "DEC R5", "ADD R1, R2", "SUB R1, R2", "MUL R1, R2", "INTDIV R1, R2",
    ]),
    ("Preset E (opcode E)", [
        "TARREG 2, LSB, R5", "TARREG 3, MSB, R5", "SETBYTE 2, 0x7F", "BUILD 2, 3, R5", "CPREG R1, R2",
    ]),
    ("Preset F (opcode F)", [
        "SETPOS R1, R2", "SETTILE R1, 0", "SETTILE R1, 3", "SETDP R7", "MOVDP R5", "SETRENDMOD 0", "SETRENDMOD 1",
        "PALETTE16", "PALETTE256", "JMR", "MOV R5", "SETREGBANK 1, 2", "CLRTILE", "CLRPALETTE", "TILEDRAW",
        "SETTILEBANK R3", "CALL 5", "GBLS R5",
    ]),
]
SHORTHANDS = ["JMR target", "JMZ target", "JNZ target", "JMG target", "JNG target", "PUSH R5", "POP R5", "JSR target",
              "RET", "HLT"]


def run(tool, *args):
    return subprocess.run([tool, *args], capture_output=True, text=True)


def assemble(source, d):
    src, out = os.path.join(d, "t.asm"), os.path.join(d, "t.bin")
    with open(src, "w") as f:
        f.write(source)
    if os.path.exists(out):
        os.remove(out)
    r = run(PPUASM, src, out)
    if r.returncode != 0 or not os.path.exists(out):
        return None
    return open(out, "rb").read()


def disassemble(data, d):
    binf = os.path.join(d, "w.bin")
    with open(binf, "wb") as f:
        f.write(data)
    out = []
    for line in run(PPUDISASM, binf).stdout.splitlines():
        m = re.match(r"\s*([0-9A-Fa-f]{4}):\s+(.*)", line)
        if m:
            out.append((int(m.group(1), 16), re.sub(r"\s+", " ", m.group(2)).strip()))
    return out


def main():
    lines = ["# PPU instruction encodings\n",
             "<!-- GENERATED by scripts/gen_ppu_docs.py from live ppuasm and ppudisasm runs: do not edit by hand. -->\n",
             "Every PPU instruction is one 16-bit word, written big-endian: a 4-bit opcode and 12 operand bits. Each row is a "
             "form `ppuasm` accepts, with the word it assembles to, split as `oooo xxxxxxxxxxxx`, and what `ppudisasm` prints "
             "for that word. What each instruction does is in [instruction-set.md](instruction-set.md).\n"]
    bad = []
    with tempfile.TemporaryDirectory() as d:
        for group, forms in FORMS:
            lines.append("## %s\n" % group)
            lines.append("| Form | Word | `oooo xxxxxxxxxxxx` | Disassembles as |")
            lines.append("|------|------|--------------------|-----------------|")
            for form in forms:
                data = assemble(form + "\n", d)
                if data is None or len(data) != 2:
                    bad.append((form, "does not assemble to one word"))
                    lines.append("| `%s` | not accepted | | |" % form)
                    continue
                word = (data[0] << 8) | data[1]
                dis = disassemble(data, d)
                text = dis[0][1] if dis else ""
                bits = format(word, "016b")
                lines.append("| `%s` | `%04X` | `%s %s` | `%s` |" % (form, word, bits[:4], bits[4:], text))
                again = assemble(text + "\n", d) if text else None
                if again != data:
                    bad.append((form, "disassembly `%s` does not assemble back to %04X" % (text, word)))
            lines.append("")

        lines.append("## Assembler shorthands\n")
        lines.append("These are not instructions: the assembler expands each into the real instructions below. "
                     "Everything that jumps to a label uses **target registers 0 and 1**, overwriting them "
                     "([assembler.md](assembler.md)). `target` is a label on the line after the shorthand, so the "
                     "addresses are small.\n")
        for sh in SHORTHANDS:
            data = assemble("%s\ntarget: NOP\n" % sh, d)
            if data is None:
                bad.append((sh, "shorthand does not assemble"))
                continue
            dis = [t for a, t in disassemble(data, d)][:-1]      # drop the trailing NOP
            lines.append("**`%s`** (%d bytes)\n" % (sh, len(data) - 2))
            lines.append("```text")
            lines.extend(dis)
            lines.append("```\n")
    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    print("wrote", OUT)
    for form, why in bad:
        print("  %-22s %s" % (form, why))
    return 0


if __name__ == "__main__":
    sys.exit(main())
